<?php
declare(strict_types=1);

namespace App\Core\Module\Config\Contracts;

/**
 * Контракт парсера конфигурационного файла (п.2 Конституции).
 *
 * Зачем: Internal\Parsers\PhpArrayParser был единственной точкой входа для
 * тестов и провайдеров — снаружи его можно было использовать только как
 * «чужую внутренность» (нарушение R3/R9). Интерфейс переводит парсер в
 * легальную границу модуля Config: потребители зависят от контракта,
 * конкретный формат (.php-массив, позже .ini/.yaml) выбирает провайдер.
 */
interface ConfigParserInterface
{
    /**
     * Распарсить файл конфигурации в ассоциативный массив.
     * Отсутствующий/битый файл — исключение RuntimeException (пусть ловит
     * boot: до установки конфигов нет, и это ошибка конфигурации, а не данных).
     *
     * @return array<string, mixed>
     */
    public function parse(string $filePath): array;
}
