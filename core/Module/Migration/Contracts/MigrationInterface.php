<?php
declare(strict_types=1);

namespace App\Core\Module\Migration\Contracts;

/**
 * Контракт одной миграции схемы БД.
 *
 * Миграция — это PHP-файл в папке migrations/, возвращающий реализацию этого
 * интерфейса (удобно — наследник AbstractMigration).
 *
 * Правила:
 *  - up()   — применить изменение (должна быть идемпотентна при повторе);
 *  - down() — откатить изменение (может быть no-op, если откат не предусмотрен);
 *  - id()   — уникальный идентификатор = имя файла без расширения;
 *             порядок исполнения — лексикографическая сортировка id
 *             (конвенция имён: <ГГГГ_ММ_ДД_HHMMSS>_<краткое_имя>).
 */
interface MigrationInterface
{
    /** Уникальный идентификатор миграции (имя файла без .php). */
    public function id(): string;

    /** Человекочитаемое описание для логов/CLI/Doctor. */
    public function description(): string;

    /** Применить миграцию. @return int количество выполненных SQL-операторов */
    public function up(): int;

    /** Откатить миграцию. @return int количество выполненных SQL-операторов */
    public function down(): int;
}
